"""Generates deploy/k8s/41-grafana.yaml (datasource + battlefield dashboard)."""
import json, os

panels, y = [], 0


def row(title):
    global y
    panels.append({"type": "row", "title": title, "gridPos": {"x": 0, "y": y, "w": 24, "h": 1}, "collapsed": False})
    y += 1


def ts(title, exprs, unit="short", w=8, x=None, stack=False):
    global y
    x = len([p for p in panels if p.get("gridPos", {}).get("y") == y and p["type"] != "row"]) * w if x is None else x
    if x + w > 24:
        y += 8
        x = 0
    panels.append({
        "type": "timeseries", "title": title, "datasource": {"type": "prometheus", "uid": "prom"},
        "gridPos": {"x": x, "y": y, "w": w, "h": 8},
        "fieldConfig": {"defaults": {"unit": unit, "custom": {"stacking": {"mode": "normal" if stack else "none"},
                                                               "fillOpacity": 15 if stack else 0}}, "overrides": []},
        "targets": [{"expr": e, "legendFormat": l, "refId": chr(65 + i)} for i, (e, l) in enumerate(exprs)],
    })


def end_row():
    global y
    y += 8


row("What users feel (client-side, attacker)")
ts("User outcomes /s", [('sum by (outcome) (rate(attacker_requests_total[30s]))', "{{outcome}}")], "reqps", stack=True)
ts("User p99 latency", [('histogram_quantile(0.99, sum by (le) (rate(attacker_latency_seconds_bucket[30s])))', "p99"),
                        ('histogram_quantile(0.5, sum by (le) (rate(attacker_latency_seconds_bucket[30s])))', "p50")], "s")
ts("User error ratio", [("user:error_ratio:1m", "errors+dropped")], "percentunit")
end_row()
row("Gateway")
ts("Gateway outcomes /s", [('sum by (outcome) (rate(gw_requests_total[30s]))', "{{outcome}}")], "reqps", stack=True)
ts("Shed reasons /s", [('sum by (reason) (rate(gw_shed_total[30s]))', "{{reason}}")], "reqps", stack=True)
ts("Queue & in-flight", [("gw_queue_depth", "queued"), ("gw_inflight", "in-flight")])
end_row()
ts("TTFT p99 by pool", [("gw:ttft_p99:1m", "{{pool}}")], "s")
ts("Retries & fallbacks /s", [('sum by (reason) (rate(gw_retries_total[30s]))', "retry {{reason}}"),
                              ('sum by (kind) (rate(gw_fallbacks_total[30s]))', "fallback {{kind}}")], "reqps")
ts("Defenses enabled", [("gw_defense_enabled", "{{defense}}")])
end_row()
row("GPU fleet")
ts("TTFT EWMA per GPU", [("worker_ttft_ewma_seconds", "{{node}}")], "s")
ts("Queue depth per GPU", [("worker_queue_depth", "{{node}}")])
ts("KV cache utilization", [("worker_kv_utilization", "{{node}}")], "percentunit")
end_row()
ts("Tokens/s per GPU", [("worker_tokens_per_second", "{{node}}")])
ts("Traffic share per GPU", [('sum by (backend) (rate(gw_backend_requests_total[30s]))', "{{backend}}")], "reqps", stack=True)
ts("Breaker / ejected / weight", [("gw_backend_breaker_state", "breaker {{backend}}"), ("gw_backend_ejected", "ejected {{backend}}"),
                                  ("gw_backend_weight", "weight {{backend}}")])
end_row()
row("Rollout & tenants")
ts("Canary weight", [("gw_canary_weight", "canary")], "percentunit")
ts("Cost $/min by version", [('sum by (version) (rate(worker_cost_dollars_total[1m])) * 60', "{{version}}")], "currencyUSD")
ts("Tenant outcomes /s", [('sum by (tenant, outcome) (rate(gw_requests_total[30s]))', "{{tenant}} {{outcome}}")], "reqps")
end_row()

dash = {"uid": "battlefield", "title": "AI Inference Battlefield", "refresh": "5s", "time": {"from": "now-15m", "to": "now"},
        "schemaVersion": 39, "panels": panels}
ds = {"apiVersion": 1, "datasources": [{"name": "Prometheus", "uid": "prom", "type": "prometheus",
                                        "url": "http://prometheus.battlefield:9090", "isDefault": True}]}
prov = {"apiVersion": 1, "providers": [{"name": "battlefield", "type": "file", "options": {"path": "/var/lib/grafana/dashboards"}}]}


def indent(s, n=4):
    return "\n".join(" " * n + l for l in s.splitlines())


yaml = f"""# Generated by deploy/observability/gen_grafana.py - edit that, not this.
apiVersion: v1
kind: ConfigMap
metadata: {{ name: grafana-provisioning, namespace: battlefield }}
data:
  datasources.yaml: |
{indent(json.dumps(ds, indent=2))}
  dashboards.yaml: |
{indent(json.dumps(prov, indent=2))}
---
apiVersion: v1
kind: ConfigMap
metadata: {{ name: grafana-dashboards, namespace: battlefield }}
data:
  battlefield.json: |
{indent(json.dumps(dash, indent=2))}
---
apiVersion: apps/v1
kind: Deployment
metadata: {{ name: grafana, namespace: battlefield }}
spec:
  replicas: 1
  selector: {{ matchLabels: {{ app: grafana }} }}
  template:
    metadata: {{ labels: {{ app: grafana }} }}
    spec:
      containers:
        - name: grafana
          image: grafana/grafana:12.1.0
          imagePullPolicy: IfNotPresent
          ports: [{{ containerPort: 3000 }}]
          env:
            - {{ name: GF_AUTH_ANONYMOUS_ENABLED, value: "true" }}
            - {{ name: GF_AUTH_ANONYMOUS_ORG_ROLE, value: Admin }}
            - {{ name: GF_AUTH_DISABLE_LOGIN_FORM, value: "true" }}
            - {{ name: GF_DASHBOARDS_DEFAULT_HOME_DASHBOARD_PATH, value: /var/lib/grafana/dashboards/battlefield.json }}
          volumeMounts:
            - {{ name: prov, mountPath: /etc/grafana/provisioning/datasources/datasources.yaml, subPath: datasources.yaml }}
            - {{ name: prov, mountPath: /etc/grafana/provisioning/dashboards/dashboards.yaml, subPath: dashboards.yaml }}
            - {{ name: dash, mountPath: /var/lib/grafana/dashboards }}
          resources:
            requests: {{ cpu: 50m, memory: 128Mi }}
            limits: {{ memory: 384Mi }}
      volumes:
        - {{ name: prov, configMap: {{ name: grafana-provisioning }} }}
        - {{ name: dash, configMap: {{ name: grafana-dashboards }} }}
---
apiVersion: v1
kind: Service
metadata: {{ name: grafana, namespace: battlefield }}
spec:
  type: NodePort
  selector: {{ app: grafana }}
  ports: [{{ port: 3000, nodePort: 30030 }}]
"""
out = os.path.join(os.path.dirname(__file__), "..", "k8s", "41-grafana.yaml")
open(out, "w").write(yaml)
print("wrote", os.path.normpath(out))
